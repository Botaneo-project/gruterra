def noms_plantes_connues():
    return [plante["nom"] for plante in PLANTES_CONNUES]


def chercher_plantes(texte):
    texte = (texte or "").strip().lower()
    if not texte:
        return noms_plantes_connues()
    return [
        plante["nom"]
        for plante in PLANTES_CONNUES
        if texte in plante["nom"].lower() or texte in plante.get("espece", "").lower()
    ]


def trouver_plante(nom):
    nom_normalise = (nom or "").strip().lower()
    for plante in PLANTES_CONNUES:
        if plante["nom"].lower() == nom_normalise:
            return plante
    return None


def resume_besoins(plante):
    if not plante:
        return "Plante non connue dans la mini base. La saisie manuelle reste possible."
    lignes = [
        f"Espèce : {plante.get('espece') or 'non renseignée'}",
        f"Type : {plante.get('type') or 'non renseigné'}",
        f"Lumière : {plante.get('lumiere') or 'non renseignée'}",
        f"Humidité du sol : {plante.get('humidite_sol') or 'non renseignée'}",
        f"Température : {plante.get('temperature') or 'non renseignée'}",
        f"Arrosage : {plante.get('arrosage') or 'non renseigné'}",
    ]
    return "\n".join(lignes)
